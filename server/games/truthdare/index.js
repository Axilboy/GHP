export function normalizeTruthDareSettings(settings = {}) {
  const target = Number(settings.targetScore);
  const deck = truthDareDefinition.settingsSchema.deck.values.includes(settings.deck) ? settings.deck : truthDareDefinition.defaultSettings.deck;
  return {
    deck,
    targetScore: Math.min(30, Math.max(5, Number.isFinite(target) ? target : truthDareDefinition.defaultSettings.targetScore)),
  };
}

function activePlayers(room) {
  return room.players.filter((player) => player.online);
}

function nextPrompt(room, random = Math.random) {
  const players = activePlayers(room);
  const turnIndex = Number.isFinite(room.truthDareTurnIndex) ? room.truthDareTurnIndex + 1 : 0;
  const activePlayer = players[turnIndex % players.length];
  const type = random() < 0.5 ? 'truth' : 'dare';
  const deck = PROMPTS[room.settings.deck] || PROMPTS.party;
  const prompts = deck[type];
  const text = prompts[Math.floor(random() * prompts.length)];
  room.truthDareTurnIndex = turnIndex;
  return {
    number: (room.round?.number || 0) + 1,
    phase: 'truthdare_turn',
    turnIndex,
    activePlayerId: activePlayer.id,
    activePlayerName: activePlayer.name,
    promptType: type,
    promptText: text,
    completed: 0,
    skipped: 0,
    result: null,
  };
}

export function createTruthDareRound(room, random = Math.random) {
  room.truthDareTurnIndex = Number.isFinite(room.truthDareTurnIndex) ? room.truthDareTurnIndex : -1;
  return nextPrompt(room, random);
}

export function advanceTruthDareRound(room, result, random = Math.random) {
  const activePlayerId = room.round?.activePlayerId;
  if (result === 'done' && activePlayerId) room.scores[activePlayerId] = (room.scores[activePlayerId] || 0) + 1;
  room.matchHistory ??= [];
  room.matchHistory.unshift({
    round: room.round?.number || 1,
    playerId: activePlayerId,
    playerName: room.round?.activePlayerName || 'Игрок',
    result,
    promptType: room.round?.promptType,
    at: Date.now(),
  });
  room.matchHistory = room.matchHistory.slice(0, 20);
  room.round = nextPrompt(room, random);
}
